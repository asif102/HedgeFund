// Helper to assemble full Finviz Sector Rotation payload with grouping by sector, industry, and stocks
export function buildFinvizSectorRotationPayload(): FinvizSectorRotationPayload {
  const stocks = SP500_STOCKS_DATASET;

  // Sector metadata: ETF Proxies and weights in S&P 500 index
  const SECTOR_META: Record<string, { etfTicker: string; weightInSP500: number }> = {
    Technology: { etfTicker: "XLK", weightInSP500: 31.8 },
    Financials: { etfTicker: "XLF", weightInSP500: 13.4 },
    Healthcare: { etfTicker: "XLV", weightInSP500: 11.9 },
    "Consumer Discretionary": { etfTicker: "XLY", weightInSP500: 10.2 },
    "Communication Services": { etfTicker: "XLC", weightInSP500: 8.9 },
    Industrials: { etfTicker: "XLI", weightInSP500: 8.4 },
    "Consumer Staples": { etfTicker: "XLP", weightInSP500: 5.8 },
    Energy: { etfTicker: "XLE", weightInSP500: 3.6 },
    Utilities: { etfTicker: "XLU", weightInSP500: 2.5 },
    "Real Estate": { etfTicker: "XLRE", weightInSP500: 2.1 },
    "Basic Materials": { etfTicker: "XLB", weightInSP500: 1.8 },
  };

  // 1. Group by Industry
  const industryMap = new Map<string, FinvizStockItem[]>();
  for (const s of stocks) {
    const arr = industryMap.get(s.industry) || [];
    arr.push(s);
    industryMap.set(s.industry, arr);
  }

  const allIndustries: FinvizIndustryGroup[] = [];
  for (const [indName, indStocks] of industryMap.entries()) {
    const sector = indStocks[0].sector;
    const count = indStocks.length;
    const avg1D = parseFloat((indStocks.reduce((a, b) => a + b.change, 0) / count).toFixed(2));
    const avg1W = parseFloat((indStocks.reduce((a, b) => a + b.perf1W, 0) / count).toFixed(2));
    const avg1M = parseFloat((indStocks.reduce((a, b) => a + b.perf1M, 0) / count).toFixed(2));
    const avg3M = parseFloat((indStocks.reduce((a, b) => a + b.perf3M, 0) / count).toFixed(2));
    const avgYTD = parseFloat((indStocks.reduce((a, b) => a + b.perfYTD, 0) / count).toFixed(2));
    const totalCapNum = indStocks.reduce((a, b) => a + b.marketCapNum, 0);

    const avgRsRatio = indStocks.reduce((a, b) => a + b.rsRatio, 0) / count;
    const avgRsMom = indStocks.reduce((a, b) => a + b.rsMomentum, 0) / count;
    let rotationQuadrant: RotationQuadrant = "Improving";
    if (avgRsRatio >= 100 && avgRsMom >= 100) rotationQuadrant = "Leading";
    else if (avgRsRatio >= 100 && avgRsMom < 100) rotationQuadrant = "Weakening";
    else if (avgRsRatio < 100 && avgRsMom < 100) rotationQuadrant = "Lagging";

    allIndustries.push({
      industry: indName,
      sector,
      stockCount: count,
      perf1D: avg1D,
      perf1W: avg1W,
      perf1M: avg1M,
      perf3M: avg3M,
      perfYTD: avgYTD,
      totalMarketCap: totalCapNum >= 1000 ? `$${(totalCapNum / 1000).toFixed(2)}T` : `$${totalCapNum}B`,
      marketCapNum: totalCapNum,
      rotationQuadrant,
      stocks: indStocks,
    });
  }

  // 2. Group by Sector
  const sectorMap = new Map<string, FinvizStockItem[]>();
  for (const s of stocks) {
    const arr = sectorMap.get(s.sector) || [];
    arr.push(s);
    sectorMap.set(s.sector, arr);
  }

  const sectors: FinvizSectorGroup[] = [];
  for (const [secName, secStocks] of sectorMap.entries()) {
    const count = secStocks.length;
    const meta = SECTOR_META[secName] || { etfTicker: "SPY", weightInSP500: 5.0 };
    const avg1D = parseFloat((secStocks.reduce((a, b) => a + b.change, 0) / count).toFixed(2));
    const avg1W = parseFloat((secStocks.reduce((a, b) => a + b.perf1W, 0) / count).toFixed(2));
    const avg1M = parseFloat((secStocks.reduce((a, b) => a + b.perf1M, 0) / count).toFixed(2));
    const avg3M = parseFloat((secStocks.reduce((a, b) => a + b.perf3M, 0) / count).toFixed(2));
    const avgYTD = parseFloat((secStocks.reduce((a, b) => a + b.perfYTD, 0) / count).toFixed(2));
    const avgRsRatio = parseFloat((secStocks.reduce((a, b) => a + b.rsRatio, 0) / count).toFixed(1));
    const avgRsMom = parseFloat((secStocks.reduce((a, b) => a + b.rsMomentum, 0) / count).toFixed(1));

    let rotationQuadrant: RotationQuadrant = "Improving";
    if (avgRsRatio >= 100 && avgRsMom >= 100) rotationQuadrant = "Leading";
    else if (avgRsRatio >= 100 && avgRsMom < 100) rotationQuadrant = "Weakening";
    else if (avgRsRatio < 100 && avgRsMom < 100) rotationQuadrant = "Lagging";

    const secIndustries = allIndustries.filter((ind) => ind.sector === secName);

    sectors.push({
      sector: secName,
      etfTicker: meta.etfTicker,
      weightInSP500: meta.weightInSP500,
      perf1D: avg1D,
      perf1W: avg1W,
      perf1M: avg1M,
      perf3M: avg3M,
      perfYTD: avgYTD,
      rotationQuadrant,
      rsRatio: avgRsRatio,
      rsMomentum: avgRsMom,
      industries: secIndustries,
      stocks: secStocks,
    });
  }

  // Sort sectors by weight in S&P 500 descending
  sectors.sort((a, b) => b.weightInSP500 - a.weightInSP500);

  // Market breadth counts
  const leadingCount = stocks.filter((s) => s.rotationQuadrant === "Leading").length;
  const improvingCount = stocks.filter((s) => s.rotationQuadrant === "Improving").length;
  const weakeningCount = stocks.filter((s) => s.rotationQuadrant === "Weakening").length;
  const laggingCount = stocks.filter((s) => s.rotationQuadrant === "Lagging").length;

  return {
    asOf: new Date().toLocaleTimeString("en-US", { hour: "2-digit", minute: "2-digit", second: "2-digit" }),
    benchmark: "S&P 500 (SPY)",
    sectors,
    allIndustries,
    allStocks: stocks,
    marketBreadth: {
      leadingCount,
      improvingCount,
      weakeningCount,
      laggingCount,
    },
  };
}
